// Generates the files derived from theme-v1.schema.json: the standalone Ajv validator and the
// small registry of schema values the runtime needs. Node only; the runtime never compiles a schema.
//   node packages/format/generate.mjs           write both files
//   node packages/format/generate.mjs --check   fail if either file differs from a fresh generation
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const SCHEMA_PATH = join(HERE, "theme-v1.schema.json");
export const VALIDATOR_PATH = join(HERE, "schema-validator.js");
export const REGISTRY_PATH = join(HERE, "schema-registry.js");

// Annotation keywords. They never change what validates, so the compiled copy leaves them out.
const ANNOTATIONS = new Set(["description", "examples", "$comment", "title", "default"]);
const MAPS = new Set(["properties", "$defs"]);

function stripAnnotations(schema) {
  if (Array.isArray(schema)) return schema.map(stripAnnotations);
  if (!schema || typeof schema !== "object") return schema;
  const out = {};
  for (const [key, value] of Object.entries(schema)) {
    if (ANNOTATIONS.has(key) || key.startsWith("x-")) continue;
    if (key === "const" || key === "enum") out[key] = value;
    else if (MAPS.has(key)) out[key] = Object.fromEntries(Object.entries(value).map(([name, sub]) => [name, stripAnnotations(sub)]));
    else out[key] = stripAnnotations(value);
  }
  return out;
}

export function readSchema() {
  const bytes = readFileSync(SCHEMA_PATH);
  return { schema: JSON.parse(bytes.toString("utf8")), sha256: createHash("sha256").update(bytes).digest("hex") };
}

// Ajv in strict mode, with the x-* keywords registered as annotations only.
export async function createAjv(options = {}) {
  const { default: Ajv2020 } = await import("ajv/dist/2020.js");
  const ajv = new Ajv2020({ strict: true, allErrors: true, ...options });
  for (const keyword of ["x-reskin", "x-cost", "x-reduced-motion"]) ajv.addKeyword({ keyword });
  return ajv;
}

// Ajv's standalone output requires two runtime helpers. Inline equivalents keep the validator a
// plain ES module with no CommonJS dependency.
const HELPERS = `// Unicode code point length, as JSON Schema counts string length.
function ucs2length(str) {
  let length = 0;
  for (let i = 0; i < str.length; i++) {
    length++;
    const code = str.charCodeAt(i);
    if (code >= 0xd800 && code <= 0xdbff && i + 1 < str.length) {
      const next = str.charCodeAt(i + 1);
      if ((next & 0xfc00) === 0xdc00) i++;
    }
  }
  return length;
}
// Deep equality of JSON values, for const and uniqueItems.
function equal(a, b) {
  if (a === b) return true;
  if (!a || !b || typeof a !== "object" || typeof b !== "object" || Array.isArray(a) !== Array.isArray(b)) return false;
  const keys = Object.keys(a);
  if (keys.length !== Object.keys(b).length) return false;
  return keys.every((key) => Object.prototype.hasOwnProperty.call(b, key) && equal(a[key], b[key]));
}
`;

export async function generateValidator() {
  const { schema, sha256 } = readSchema();
  const { default: standaloneCode } = await import("ajv/dist/standalone/index.js");
  // Messages are written by validate.js, so Ajv's English messages are left out.
  const ajv = await createAjv({ messages: false, code: { source: true, esm: true } });
  let code = standaloneCode(ajv, ajv.compile(stripAnnotations(schema)));
  const requires = {
    'require("ajv/dist/runtime/ucs2length").default': "ucs2length",
    'require("ajv/dist/runtime/equal").default': "equal",
  };
  for (const [from, to] of Object.entries(requires)) code = code.split(from).join(to);
  if (/\brequire\(/.test(code)) throw new Error("Ajv standalone output has an unexpected require()");
  // Minified so the validator stays small in every bundle; the schema and this generator are the
  // reviewable source, and check:schema proves the file matches a fresh generation.
  const { transform } = await import("esbuild");
  const { code: minified } = await transform(`${HELPERS}${code.replace(/^"use strict";/, "")}`, { format: "esm", minify: true, legalComments: "none", charset: "utf8" });
  return `// Generated by packages/format/generate.mjs from theme-v1.schema.json (sha256 ${sha256}).
// Do not edit. Regenerate with: node packages/format/generate.mjs
${minified}`;
}

const round = (value) => JSON.stringify(value, null, 2);

export function generateRegistry() {
  const { schema, sha256 } = readSchema();
  const x = schema["x-reskin"];
  const effects = {};
  for (const id of Object.keys(schema.properties.effects.properties)) {
    const params = {};
    for (const [name, def] of Object.entries(schema.$defs[`effect-${id}`].properties)) {
      params[name] = { ...(def.enum ? { enum: def.enum } : { type: def.type, minimum: def.minimum, maximum: def.maximum }), default: def.default };
    }
    effects[id] = params;
  }
  const fonts = [{ id: "system", family: null, weight: null, minimumAccentPx: null }].concat(
    x.fonts.map(({ id, family, weight, minimumAccentPx }) => ({ id, family, weight, minimumAccentPx })),
  );
  const slots = Object.fromEntries(Object.entries(schema.properties.flavor.properties.slots.properties).map(([id, def]) => [id, { maxLength: def.maxLength }]));
  const text = Object.fromEntries(["name", "author", "description", "inspiredBy"].map((key) => [key, { maxLength: schema.properties[key].maxLength }]));
  text.tags = { maxItems: schema.properties.tags.maxItems, maxLength: schema.properties.tags.items.maxLength };
  return `// Generated by packages/format/generate.mjs from theme-v1.schema.json. Do not edit.
// Values the runtime needs from the schema without loading it.

export const SCHEMA_SHA256 = ${JSON.stringify(sha256)};
export const SCHEMA_ID = ${JSON.stringify(schema.$id)};

// Effect parameters in schema order, with bounds and the engine default for an omitted value.
export const EFFECT_PARAMETERS = ${round(effects)};

// "system" ships no file and has no family.
export const FONTS = ${round(fonts)};

export const FLAVOR_SLOTS = ${round(slots)};

export const TEXT_LIMITS = ${round(text)};

// The minimal embedded example, used by the AI prompt.
export const MINIMAL_EXAMPLE = ${JSON.stringify(schema.examples[0])};
`;
}

export async function generated() {
  return { [VALIDATOR_PATH]: await generateValidator(), [REGISTRY_PATH]: generateRegistry() };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [path, text] of Object.entries(await generated())) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current === text) continue;
    if (check) {
      console.error(`${path} is out of date. Run node packages/format/generate.mjs`);
      stale++;
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${path}`);
    }
  }
  process.exitCode = stale ? 1 : 0;
}
