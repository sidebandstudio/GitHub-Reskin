// Builds userscript/github-reskin.user.js from the extension and userscript/main.js.
// Run after changing either: node scripts/userscript.mjs
import { realpathSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const REPO = "https://github.com/sidebandstudio/GitHub-Reskin";
const RAW = "https://raw.githubusercontent.com/sidebandstudio/GitHub-Reskin/main";
const OUTPUT = "userscript/github-reskin.user.js";
// The upstream notice for the Primer colors in extension/github-modes.js, which this script includes.
const NOTICE = "licenses/primer-primitives.txt";

const file = (path) => new URL(`../${path}`, import.meta.url);
// Checkouts can have either line ending, so the build always uses LF.
const read = async (path) => (await readFile(file(path), "utf8")).replace(/\r\n/g, "\n");

export async function build() {
  const manifest = JSON.parse(await read("extension/manifest.json"));
  const { matches, js } = manifest.content_scripts[0];
  const icon = (await readFile(file("extension/icons/icon-32.png"))).toString("base64");
  const html = (await read("extension/popup.html"))
    .match(/<main[\s\S]*<\/main>/)[0]
    .replace('src="icons/icon-32.png"', `src="data:image/png;base64,${icon}"`);
  const paths = ["userscript/main.js", ...[...js, "popup.js"].map((name) => `extension/${name}`)];
  const scripts = await Promise.all(paths.map(read));
  const notice = await read(NOTICE);
  if (notice.includes("*/")) throw new Error(`${NOTICE} would end its comment early`);

  return `// ==UserScript==
// @name         ${manifest.name}
// @namespace    ${REPO}
// @version      ${manifest.version}
// @description  ${manifest.description}
// @homepageURL  ${REPO}
// @icon         ${RAW}/extension/icons/icon-128.png
${matches.map((match) => `// @match        ${match}`).join("\n")}
// @run-at       document-start
// @inject-into  content
// @noframes
// @grant        GM.getValue
// @grant        GM.setValue
// @grant        GM.registerMenuCommand
// @downloadURL  ${RAW}/${OUTPUT}
// @updateURL    ${RAW}/${OUTPUT}
// ==/UserScript==
// Generated by scripts/userscript.mjs. Do not edit by hand.
/*
${notice}*/
(function () {
"use strict";
const POPUP_CSS = ${JSON.stringify(await read("extension/popup.css"))};
const POPUP_HTML = ${JSON.stringify(html)};
${scripts.join("\n")}
})();
`;
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(file(OUTPUT), await build());
  console.log(`Wrote ${OUTPUT}`);
}
